function cell(
  agent: Emission,
  workspace: Emission,
  options: {
    basis?: CellBasis;
    testId?: string | null;
    consequence?: string | null;
  } = {},
): CapabilityCell {
  return {
    agent,
    workspace,
    basis: options.basis ?? 'emitted',
    testId: options.testId ?? null,
    consequence: options.consequence ?? null,
  };
}

/** A cell that is refused in every mode: the evidence is a planner test. */
function refused(consequence: string, testId: string): CapabilityCell {
  return cell('dropped', 'dropped', { basis: 'probe', testId, consequence });
}

function claudeWorkspaceDropped(capability: string): string {
  return `profile mode is not supported on claudecode in this release, so no workspace-level ${capability} is written`;
}

function claudeNotCarried(kind: string): string {
  return `claudecode does not carry ${kind} in this release; a persona that references one is refused with F001`;
}

function opencodeWorkspaceOnly(kind: string, target: string): string {
  switch (kind) {
    case 'skill':
      return `skills are workspace level only on ${target}, so an agent mode persona loses this skill; profile mode carries it`;
    case 'command':
      return `commands are workspace level only on ${target}, so an agent mode persona loses its command set; profile mode carries it`;
    case 'mcp':
      return `${target} configures MCP servers at the workspace level, not per agent, so an agent mode persona loses its server; profile mode carries it`;
    default:
      return `${target} carries hooks at the workspace level only, as a generated plugin, so an agent mode persona loses its hook (W101, high); profile mode carries representable events only`;
  }
}

