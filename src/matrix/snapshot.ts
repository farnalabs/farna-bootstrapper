/**
 * The measured capability matrix.
 *
 * A cell answers two questions with one value, so it carries two emissions:
 *
 * - `agent`: can the capability land in the artefact for one persona, visible
 *   only to that persona?
 * - `workspace`: can it land at the workspace level, visible to every persona?
 *
 * The value vocabulary is closed. `unknown` is not a soft `native`: it means
 * the behaviour was never measured, so it is never presented as a tick.
 *
 * The data here is the committed measured record for this release. It is not
 * generated by a probe in this slice, so every measured cell is backed by a
 * golden test that pins the emitted bytes; `basis` says which kind of evidence
 * it is. A cell is edited only in the same change that moves the test observing
 * it.
 */
export type Emission = 'native' | 'emulated' | 'dropped' | 'unknown';

export type TargetStatus = 'promised' | 'unverified';

export type CellBasis = 'probe' | 'emitted' | 'upstream-doc' | 'none';

export type CapabilityCell = {
  agent: Emission;
  workspace: Emission;
  basis: CellBasis;
  /**
   * The test that observes the cell's claim, repository-relative: the golden
   * test that pins the emitted bytes, or the planner test that proves a
   * refusal. `null` when no single test observes the claim.
   */
  testId: string | null;
  /** What the emission means for the author; required for a non-native value. */
  consequence: string | null;
};

/** One product permission key as the target carries it, per persona. */
export type PermissionKeyCell = {
  emission: Emission;
  /** The diagnostic a declaration raises, or `null` when it is carried plainly. */
  code: string | null;
  consequence: string | null;
};

export type TargetMatrix = {
  id: SupportedTarget;
  status: TargetStatus;
  /** Whether a persona is the primary session or a callable subagent. */
  agentReach: 'primary' | 'subagent';
  cells: Record<Capability, CapabilityCell>;
  permissionKeys: Record<PermissionCategory, PermissionKeyCell>;
};

export type CapabilitySnapshot = {
  schemaVersion: 1;
  renderer: { name: string; version: string };
  targets: TargetMatrix[];
};

/**
 * The reported order. It follows the source model: what a persona reads
 * (rule), what it runs as (model), what it may do (permission), then the
 * workspace-level kinds that are carried only by profile mode.
 */
export const MATRIX_CAPABILITIES: readonly Capability[] = [
  'rule',
  'model',
  'permission',
  'skill',
  'command',
  'mcp',
  'hook',
];

const CLAUDE_TEST = 'tests/golden/builder-python.test.ts';
