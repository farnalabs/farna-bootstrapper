/**
 * Refuse a snapshot that cannot be published. This is the structural guard
 * behind "an unknown cell is never a tick": a promised target must have a
 * measured emission on both axes for every capability. `unknown` remains valid
 * on an unverified target, where the whole row is labelled unverified.
 *
 * F010 is the design's code for a matrix that does not match the build: it
 * fails the report rather than rendering a claim nobody measured.
 */
export function verifySnapshot(snapshot: CapabilitySnapshot, rendererVersion?: string): void {
  if (rendererVersion !== undefined && snapshot.renderer.version !== rendererVersion) {
    throw new FarnaError(
      'F010_RENDERER_MISMATCH',
      `the capability snapshot records ${snapshot.renderer.name} ${snapshot.renderer.version} but this build pins ${rendererVersion}`,
      {
        subject: snapshot.renderer.name,
        action:
          'measure the matrix against the pinned renderer and update the snapshot in the same change',
      },
    );
  }
  const ids = snapshot.targets.map((target) => target.id);
  for (const supported of SUPPORTED_TARGETS) {
    const matches = ids.filter((id) => id === supported).length;
    if (matches !== 1) {
      throw new FarnaError(
        'F010_RENDERER_MISMATCH',
        `the capability snapshot has ${matches} row(s) for the supported target "${supported}"`,
        {
          subject: supported,
          action: 'give every supported target exactly one measured row',
        },
      );
    }
  }
  for (const target of snapshot.targets) {
    if (target.status !== 'promised') {
      continue;
    }
    for (const capability of MATRIX_CAPABILITIES) {
      const measured = target.cells[capability];
      if (measured.agent === 'unknown' || measured.workspace === 'unknown') {
        throw new FarnaError(
          'F010_RENDERER_MISMATCH',
          `the promised target "${target.id}" has an unmeasured "${capability}" cell`,
          {
            subject: `${target.id}/${capability}`,
            action: 'measure the cell, or mark the target unverified',
          },
        );
      }
    }
  }
}

/** The one glyph each emission renders as. No value renders blank. */
export function emissionGlyph(emission: Emission): string {
  switch (emission) {
    case 'native':
      return '[x]';
    case 'emulated':
      return '[~]';
    case 'dropped':
      return '[ ]';
    case 'unknown':
      return '[?]';
    default: {
      const exhaustive: never = emission;
      return exhaustive;
    }
  }
}

/** The word each emission renders as. `unknown` is always "not measured". */
export function emissionWord(emission: Emission): string {
  return emission === 'unknown' ? 'not measured' : emission;
}

/** Every permission category, in the product's declared order. */
export function permissionCategories(): readonly PermissionCategory[] {
  return PERMISSION_CATEGORIES;
}
